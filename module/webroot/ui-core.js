// Interoperability only: pass explicit WASM bytes and marshal the Rust policy API.
import init,* as rust from './rhso_webui.js';
import {wasmBase64} from './rhso_webui_bytes.js';
export const ready=init({module_or_path:Uint8Array.from(atob(wasmBase64),c=>c.charCodeAt(0))});
await ready;
const marshal=value=>JSON.stringify(value??null);
const call=(fn,...args)=>{try{return fn(...args);}catch(error){throw error instanceof Error?error:new Error(String(error));}};
const decoded=(fn,...args)=>JSON.parse(call(fn,...args));
const policy=decoded(rust.policy_json);
export const stackTargets=policy.targets,stackProfiles=policy.profiles,stackStates=policy.states;
export const encodeRequest=(command,args={})=>call(rust.encode_request,command,marshal(args));
export const readResult=stdout=>decoded(rust.read_result,stdout);
export const safeText=(value,fallback='Not established')=>call(rust.safe_text,marshal(value),fallback);
export const list=value=>decoded(rust.list_json,marshal(value));
export const selectionValue=(id,box,key,algorithm)=>call(rust.selection_value,id,box,key,algorithm);
export const targetCompactionCounts=value=>decoded(rust.compaction_counts,marshal(value));
export const privateAPIConfigPath=value=>call(rust.private_api_path,value);
export const apiStatusView=value=>decoded(rust.api_status_view,marshal(value));
export const redactedAPIResponse=value=>decoded(rust.redact_api,marshal(value));
export const stackStatusView=value=>decoded(rust.stack_status_view,marshal(value));
export const stackPackageList=value=>decoded(rust.stack_package_list,value);
export const stackPlanView=value=>decoded(rust.stack_plan_view,marshal(value));
export const redactedStackError=value=>decoded(rust.redact_stack,marshal(value));
export const evidenceBinding=value=>decoded(rust.evidence_binding,marshal(value));
